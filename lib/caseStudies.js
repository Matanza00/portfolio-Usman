// Google Fonts stylesheet for the type specimen: only this project's faces.
export function fontsHref(c) {
  if (!c.fonts) return null;
  const fams = new Map();
  for (const [family, , weight] of c.fonts.weights) {
    if (!fams.has(family)) fams.set(family, new Set());
    fams.get(family).add(weight);
  }
  if (fams.has(c.fonts.body)) fams.get(c.fonts.body).add(400);
  const q = [...fams]
    .map(([family, ws]) => `family=${family.replace(/ /g, "+")}:wght@${[...ws].sort((a, b) => a - b).join(";")}`)
    .join("&");
  return `https://fonts.googleapis.com/css2?${q}&display=swap`;
}
